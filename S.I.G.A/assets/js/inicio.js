const idiomaHtmlPorCodigo = { pt: "pt-BR", en: "en", es: "es" };
const chaveArmazenamentoIdioma = "siga-idioma";

const armazenamentoIdioma = {
  ler() {
    try {
      let idiomaSalvo = localStorage.getItem(chaveArmazenamentoIdioma);
      if (!idiomaSalvo) {
        idiomaSalvo = localStorage.getItem("siga-lang");
        if (idiomaSalvo) {
          localStorage.setItem(chaveArmazenamentoIdioma, idiomaSalvo);
          localStorage.removeItem("siga-lang");
        }
      }
      return idiomaSalvo;
    } catch (error) {
      return null;
    }
  },
  salvar(codigoIdioma) {
    try {
      localStorage.setItem(chaveArmazenamentoIdioma, codigoIdioma);
      localStorage.removeItem("siga-lang");
    } catch (error) {
      // A seleção continua ativa na página mesmo sem persistência.
    }
  }
};

document.addEventListener("DOMContentLoaded", () => {
  const elementoRaiz = document.documentElement;
  const seletorIdioma = document.querySelector(".seletor-idioma");
  const botaoIdioma = document.querySelector(".botao-idioma");
  const opcoesIdioma = document.querySelectorAll(".lista-idiomas li");
  const bandeiraPrincipal = botaoIdioma.querySelector(".bandeira");
  const rotuloIdioma = botaoIdioma.querySelector("span");

  let idiomaAtual = "pt";

  function aplicarIdioma(codigoIdioma) {
    const textos = traducoesPorIdioma[codigoIdioma];
    if (!textos) return;
    idiomaAtual = codigoIdioma;

    document.querySelectorAll("[data-traducao]").forEach(el => {
      if (textos[el.dataset.traducao] !== undefined) el.textContent = textos[el.dataset.traducao];
    });

    // As traduções com marcação usam apenas conteúdo estático deste arquivo.
    document.querySelectorAll("[data-traducao-html]").forEach(el => {
      if (textos[el.dataset.traducaoHtml] !== undefined) el.innerHTML = textos[el.dataset.traducaoHtml];
    });
    document.querySelectorAll("[data-traducao-aria]").forEach(el => {
      if (textos[el.dataset.traducaoAria] !== undefined) el.setAttribute("aria-label", textos[el.dataset.traducaoAria]);
    });

    document.title = textos.titulo_pagina;
    elementoRaiz.lang = idiomaHtmlPorCodigo[codigoIdioma];

    opcoesIdioma.forEach(opcao => {
      const selecionada = opcao.dataset.idioma === codigoIdioma;
      opcao.setAttribute("aria-selected", selecionada ? "true" : "false");
      if (selecionada) {
        const bandeira = opcao.querySelector(".bandeira");
        bandeiraPrincipal.src = bandeira.src;
        bandeiraPrincipal.alt = bandeira.alt;
      }
    });
    rotuloIdioma.textContent = codigoIdioma.toUpperCase();
    if (typeof window.atualizarRotuloTema === "function") window.atualizarRotuloTema();
  }

  function abrirMenu() {
    seletorIdioma.classList.add("aberto");
    botaoIdioma.setAttribute("aria-expanded", "true");
    opcoesIdioma.forEach(opcao => opcao.setAttribute("tabindex", "0"));
    opcoesIdioma[0] && opcoesIdioma[0].focus();
  }

  function fecharMenu(devolverFoco = false) {
    seletorIdioma.classList.remove("aberto");
    botaoIdioma.setAttribute("aria-expanded", "false");
    opcoesIdioma.forEach(opcao => opcao.setAttribute("tabindex", "-1"));
    if (devolverFoco) botaoIdioma.focus();
  }

  botaoIdioma.addEventListener("click", (evento) => {
    evento.stopPropagation();
    seletorIdioma.classList.contains("aberto") ? fecharMenu(true) : abrirMenu();
  });

  botaoIdioma.addEventListener("keydown", (evento) => {
    if (evento.key === "Escape") fecharMenu(true);
  });

  document.addEventListener("click", (evento) => {
    if (!seletorIdioma.contains(evento.target)) fecharMenu();
  });

  opcoesIdioma.forEach((opcao, indice) => {
    opcao.addEventListener("click", () => selecionarIdioma(opcao));

    opcao.addEventListener("keydown", (evento) => {
      if (evento.key === "Enter" || evento.key === " ") {
        evento.preventDefault();
        selecionarIdioma(opcao);
      } else if (evento.key === "Escape") {
        fecharMenu(true);
      } else if (evento.key === "ArrowDown") {
        evento.preventDefault();
        (opcoesIdioma[indice + 1] || opcoesIdioma[0]).focus();
      } else if (evento.key === "ArrowUp") {
        evento.preventDefault();
        (opcoesIdioma[indice - 1] || opcoesIdioma[opcoesIdioma.length - 1]).focus();
      } else if (evento.key === "Tab") {
        const ultimaOpcao = indice === opcoesIdioma.length - 1;
        const primeiraOpcao = indice === 0;
        if ((!evento.shiftKey && ultimaOpcao) || (evento.shiftKey && primeiraOpcao)) fecharMenu();
      }
    });
  });

  function selecionarIdioma(opcao) {
    const codigoIdioma = opcao.dataset.idioma;
    aplicarIdioma(codigoIdioma);
    armazenamentoIdioma.salvar(codigoIdioma);
    fecharMenu(true);
  }

  const dialogo = document.getElementById("dialogo_informacoes");
  const tituloDialogo = document.getElementById("titulo_informacoes");
  const textoDialogo = document.getElementById("texto_informacoes");

  const nomesTitulosPorDialogo = {
    suporte: "rodape_suporte",
    termos: "rodape_termos",
    privacidade: "rodape_privacidade"
  };
  const nomesTextosPorDialogo = {
    suporte: "texto_suporte",
    termos: "texto_termos",
    privacidade: "texto_privacidade"
  };

  document.querySelectorAll("[data-dialogo]").forEach(linkRodape => {
    linkRodape.addEventListener("click", (evento) => {
      evento.preventDefault();
      const nomeDialogo = linkRodape.dataset.dialogo;
      const textosDialogo = traducoesPorIdioma[idiomaAtual];
      tituloDialogo.textContent = textosDialogo[nomesTitulosPorDialogo[nomeDialogo]];
      textoDialogo.textContent = textosDialogo[nomesTextosPorDialogo[nomeDialogo]];
      if (typeof dialogo.showModal === "function") dialogo.showModal();
      else dialogo.setAttribute("open", "");
    });
  });

  function fecharDialogo() {
    if (typeof dialogo.close === "function") {
      dialogo.close();
    } else {
      dialogo.removeAttribute("open");
    }
  }

  document.getElementById("fechar_informacoes").addEventListener("click", fecharDialogo);
  dialogo.addEventListener("click", (evento) => { if (evento.target === dialogo) fecharDialogo(); });

  // Navegação interna sem poluir a URL (sem #inicio, #titulo_sobre, #secretaria...)
  function irParaSecao(alvo) {
    if (!alvo) return;
    if (alvo === document.body || alvo === document.documentElement) {
      window.scrollTo({ top: 0 });
    } else {
      alvo.scrollIntoView({ block: "start" });
      // Acessibilidade: leva o foco do teclado/leitor de tela para a seção
      if (!alvo.hasAttribute("tabindex")) alvo.setAttribute("tabindex", "-1");
      alvo.focus({ preventScroll: true });
    }
  }

  function limparHashDaUrl() {
    if (!window.location.hash) return;
    history.replaceState(null, "", window.location.pathname + window.location.search);
  }

  document.querySelectorAll('a[href^="#"]:not([href="#"]):not([data-dialogo])').forEach(link => {
    link.addEventListener("click", (evento) => {
      const alvo = document.getElementById(decodeURIComponent(link.getAttribute("href").slice(1)));
      if (!alvo) return;
      evento.preventDefault();
      irParaSecao(alvo);
      limparHashDaUrl();
    });
  });

  // Se a página for aberta/atualizada já com um #hash, vai até a seção e limpa a URL
  if (window.location.hash.length > 1) {
    const alvoInicial = document.getElementById(decodeURIComponent(window.location.hash.slice(1)));
    limparHashDaUrl();
    if (alvoInicial) window.addEventListener("load", () => irParaSecao(alvoInicial), { once: true });
  }

  const idiomaSalvo = armazenamentoIdioma.ler();
  aplicarIdioma(traducoesPorIdioma[idiomaSalvo] ? idiomaSalvo : "pt");
});